function lesionsFor(patientId: string, seed: number): Lesion[] {
  const locations = [
    "Periventricular region",
    "Juxtacortical region",
    "Infratentorial region",
    "Spinal-adjacent white matter",
    "Deep white matter, frontal lobe",
    "Corpus callosum",
    "Periventricular region (left)",
  ];
  const statuses: Lesion["status"][] = ["stable", "new", "enlarging", "stable", "resolved", "stable", "new"];
  return Array.from({ length: seed }).map((_, i) => ({
    id: `${patientId}-L${i + 1}`,
    index: i + 1,
    volumeML: Number((0.15 + ((i * 37) % 50) / 100).toFixed(2)),
    location: locations[i % locations.length],
    status: statuses[i % statuses.length],
  }));
}

